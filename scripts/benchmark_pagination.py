"""EXPLAIN real repository queries in disposable, transaction-local schemas.

Run: python -m scripts.benchmark_pagination --rows 100000 [--full-plans]
Uses DATABASE_URL; application tables are never read or written. Synthetic data
contains timestamp ties, soft deletes, multiple tenants, and hot/sparse users.
All benchmark tables and rows are rolled back, including on failure.
"""
