def synthetic_id(value: str) -> UUID:
	return UUID(hashlib.md5(value.encode(), usedforsecurity=False).hexdigest())


class QueryCapture:
	"""Capture the actual Select generated by a repository, without executing it."""
	statement: Any

	async def scalars(self, statement: Any) -> QueryCapture:
		self.statement = statement
		return self

	async def execute(self, statement: Any) -> QueryCapture:
		self.statement = statement
		return self

	async def scalar(self, statement: Any) -> None:
		self.statement = statement

	async def flush(self) -> None:
		pass

	def all(self) -> list[Any]:
		return []

	def mappings(self) -> list[Any]:
		return []


async def seed(session: AsyncSession, schemas: dict[str, str], rows: int) -> None:
	"""Explicit benchmark data, isolated from migrations and application runtime."""
	c, p, n, s = (schemas[name] for name in ("communities", "content", "notifications", "social_graph"))
	stamp = "TIMESTAMPTZ '2026-01-01 00:00:00+00' + (g / 5) * INTERVAL '1 second'"
	queries = [
		f"""INSERT INTO {c}.communities (id, name, visibility, owner_id, created_at)
		SELECT md5('community:' || g)::uuid, 'Community ' || g,
		CASE WHEN g % 10 < 7 THEN 'public' ELSE 'private' END, md5('viewer')::uuid, {stamp}
		FROM generate_series(1, :community_rows) g""",
		f"""INSERT INTO {c}.community_roles (id, name, can_manage_members, can_read_roles)
		VALUES (md5('role')::uuid, 'member', false, false)""",
		f"""INSERT INTO {p}.posts (id, author_id, community_id, body, created_at, updated_at, is_deleted)
		SELECT md5('post:' || g)::uuid,
		CASE WHEN g % 3 = 0 THEN md5('author')::uuid ELSE md5('author:' || (g % 200))::uuid END,
		CASE WHEN g % 5 <> 0 THEN md5('community:1')::uuid ELSE md5('community:' || (g % 100 + 1))::uuid END,
		repeat('Representative post body. ', 8), {stamp}, {stamp}, g % 10 = 0
		FROM generate_series(1, :rows) g""",
		f"""INSERT INTO {n}.notifications (id, recipient_id, type, payload, is_read, created_at)
		SELECT md5('notification:' || g)::uuid,
		CASE WHEN g % 5 <> 0 THEN md5('viewer')::uuid ELSE md5('recipient:' || (g % 100))::uuid END,
		'post_created', jsonb_build_object('post_id', md5('post:' || g)), g % 4 <> 0, {stamp}
		FROM generate_series(1, :rows) g""",
		f"""INSERT INTO {c}.community_members (id, user_id, community_id, role_id, joined_at)
		SELECT md5('member:' || g)::uuid, md5('member-user:' || g)::uuid,
		CASE WHEN g % 5 <> 0 THEN md5('community:1')::uuid ELSE md5('community:' || (g % 100 + 1))::uuid END,
		md5('role')::uuid, {stamp} FROM generate_series(1, :rows) g""",
		f"""INSERT INTO {s}.friend_requests (id, requester_id, receiver_id, status, created_at, updated_at)
		SELECT md5('request:' || g)::uuid, md5('requester:' || g)::uuid,
		CASE WHEN g % 5 <> 0 THEN md5('viewer')::uuid ELSE md5('receiver:' || (g % 100))::uuid END,
		CASE WHEN g % 7 = 0 THEN 'REJECTED' ELSE 'PENDING' END, {stamp}, {stamp}
		FROM generate_series(1, :rows) g""",
		f"""INSERT INTO {s}.friendships (user_low, user_high, created_at)
		SELECT least(md5('friend:' || g)::uuid, md5('viewer')::uuid),
		greatest(md5('friend:' || g)::uuid, md5('viewer')::uuid), {stamp}
		FROM generate_series(1, :rows) g""",
	]
	for query in queries:
		await session.execute(text(query), {"rows": rows, "community_rows": max(100, rows // 10)})
	for schema, table in ((c, "communities"), (c, "community_members"), (p, "posts"),
			(n, "notifications"), (s, "friend_requests"), (s, "friendships")):
		await session.execute(text(f"ANALYZE {schema}.{table}"))


def plan_nodes(plan: dict[str, Any]) -> list[dict[str, Any]]:
	return [plan, *(node for child in plan.get("Plans", []) for node in plan_nodes(child))]


async def explain(session: AsyncSession, statement: Any, schemas: dict[str, str]) -> dict[str, Any]:
	connection = await session.connection()
	sql = str(statement.compile(dialect=connection.dialect, schema_translate_map=schemas,
		render_schema_translate=True, compile_kwargs={"literal_binds": True}))
	result = await connection.exec_driver_sql("EXPLAIN (ANALYZE, BUFFERS, FORMAT JSON) " + sql)
	return result.scalar_one()[0]


async def benchmark(session: AsyncSession, schemas: dict[str, str], rows: int, *, deep_offset: int = 50000) -> list[dict[str, Any]]:
	await seed(session, schemas, rows)
	capture: Any = QueryCapture()
	content, notifications = ContentRepository(capture), NotificationRepository(capture)
	communities, social = CommunityRepository(capture), SocialGraphRepository(capture)
	community, author, user = synthetic_id("community:1"), synthetic_id("author"), synthetic_id("viewer")
	accessible = [synthetic_id(f"community:{i}") for i in range(1, 101) if i % 10 < 7]
	cases: list[tuple[str, Callable[..., Awaitable[Any]], tuple[Any, ...], str | None]] = [
		("community_posts", content.get_community_posts, (community, 51), "created_at"),
		("community_posts_sparse", content.get_community_posts, (synthetic_id("community:6"), 51), "created_at"),
		("author_posts", content.get_user_posts, (author, accessible, 51), "created_at"),
		("author_posts_sparse", content.get_user_posts, (synthetic_id("author:1"), accessible, 51), "created_at"),
		("feed_broad", content.get_feed, (accessible, 51), "created_at"),
		("feed_sparse", content.get_feed, ([synthetic_id("community:6")], 51), "created_at"),
		("feed_sparse_multiple", content.get_feed, ([synthetic_id(f"community:{i}") for i in (6, 16, 26)], 51), "created_at"),
		("notifications", notifications.get_for_user, (user, 51), "created_at"),
		("notifications_sparse", notifications.get_for_user, (synthetic_id("recipient:5"), 51), "created_at"),
		("public_communities", communities.list_public, (51,), "created_at"),
		("members", communities.list_members, (community, 51), "joined_at"),
		("member_id_batches", communities.list_member_ids, (community, 501), "joined_at"),
		("pending_requests", social.get_pending_requests, (user, 51), "created_at"),
		("pending_requests_sparse", social.get_pending_requests, (synthetic_id("receiver:5"), 51), "created_at"),
		("friends", social.get_friends, (user, 51), None),
	]
	reports = []
	for name, method, args, time_field in cases:
		await method(*args, None)
		first_statement = capture.statement
		if name == "friends":
			friend_id = case((Friendship.user_low == user, Friendship.user_high), else_=Friendship.user_low)
			baseline = select(friend_id.label("friend_id")).where(or_(Friendship.user_low == user, Friendship.user_high == user)).order_by(friend_id)
		else:
			baseline = first_statement.limit(None).offset(None)
		count = await session.scalar(select(func.count()).select_from(baseline.order_by(None).subquery()))
		assert count is not None and count > 1
		offset = min(deep_offset, count // 2)
		anchor_row = (await session.execute(baseline.offset(offset - 1).limit(1))).one()
		if time_field is None:
			anchor = anchor_row[0]
		elif hasattr(anchor_row[0], time_field):
			anchor = (getattr(anchor_row[0], time_field), anchor_row[0].id)
		else:
			anchor = (anchor_row._mapping[time_field], anchor_row._mapping["id"])
		await method(*args, anchor)
		deep_statement = capture.statement
		limit = args[-1]
		for mode, statement in (("first", first_statement), ("cursor_deep", deep_statement), ("offset_deep", baseline.offset(offset).limit(limit))):
			plan = await explain(session, statement, schemas)
			nodes = plan_nodes(plan["Plan"])
			reports.append({"query": name, "mode": mode, "matching_rows": count, "offset": offset if mode != "first" else 0,
				"execution_ms": plan["Execution Time"], "shared_blocks": plan["Plan"].get("Shared Hit Blocks", 0) + plan["Plan"].get("Shared Read Blocks", 0),
				"indexes": sorted({node["Index Name"] for node in nodes if "Index Name" in node}),
				"scan_rows": sum((node.get("Actual Rows", 0) + node.get("Rows Removed by Filter", 0) + node.get("Rows Removed by Index Recheck", 0)) * node.get("Actual Loops", 1) for node in nodes if "Scan" in node["Node Type"]),
				"plan": plan})
	operations: list[tuple[str, Callable[..., Awaitable[Any]], tuple[Any, ...]]] = [
		("pending_pair_lookup", social.get_pending_request_for_pair, (user, synthetic_id("requester:101"))),
		("mark_unread_read_sparse", notifications.mark_all_read, (synthetic_id("recipient:20"),)),
	]
	for name, operation, args in operations:
		await operation(*args)
		plan = await explain(session, capture.statement, schemas)
		nodes = plan_nodes(plan["Plan"])
		reports.append({"query": name, "mode": "operation", "execution_ms": plan["Execution Time"],
			"shared_blocks": plan["Plan"].get("Shared Hit Blocks", 0) + plan["Plan"].get("Shared Read Blocks", 0),
			"indexes": sorted({node["Index Name"] for node in nodes if "Index Name" in node}),
			"scan_rows": sum((node.get("Actual Rows", 0) + node.get("Rows Removed by Filter", 0)) * node.get("Actual Loops", 1) for node in nodes if "Scan" in node["Node Type"]),
			"plan": plan})
	return reports


async def main(rows: int, deep_offset: int, full_plans: bool) -> None:
	from app.modules.model_registry import MODEL_MODULES
	for module in MODEL_MODULES:
		importlib.import_module(module)
	schemas = {name: f"pagination_bench_{uuid4().hex[:12]}_{name}" for name in SCHEMA_NAMES}
	engine = create_async_engine(settings.DATABASE_URL, execution_options={"schema_translate_map": schemas})
	try:
		async with engine.connect() as connection:
			transaction = await connection.begin()
			try:
				for schema in schemas.values():
					await connection.execute(CreateSchema(schema))
				for metadata in ALL_METADATA:
					await connection.run_sync(metadata.create_all)
				async with AsyncSession(bind=connection, expire_on_commit=False, join_transaction_mode="create_savepoint") as session:
					reports = await benchmark(session, schemas, rows, deep_offset=deep_offset)
					if not full_plans:
						for report in reports:
							report.pop("plan")
						print(json.dumps({"rows_per_large_table": rows, "reports": reports}, indent=2))
			finally:
				await transaction.rollback()
	finally:
		await engine.dispose()


if __name__ == "__main__":
	parser = argparse.ArgumentParser(description=__doc__)
	parser.add_argument("--rows", type=int, default=100000)
	parser.add_argument("--deep-offset", type=int, default=50000)
	parser.add_argument("--full-plans", action="store_true")
	args = parser.parse_args()
	if args.rows < 1000 or args.deep_offset < 1:
		parser.error("--rows must be at least 1000; --deep-offset must be positive")
	asyncio.run(main(args.rows, args.deep_offset, args.full_plans))
